// Regenerates THIRD_PARTY_NOTICES.md: Rust crates via cargo-about, JavaScript
// modules actually bundled via Vite's build.license, and the bundled fonts.
// Run with `npm run notices` after changing dependencies. Needs cargo-about
// (`cargo install cargo-about --locked`) on PATH.
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "vite";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outFile = path.join(root, "THIRD_PARTY_NOTICES.md");
const ownCrate = "hablo";

function fence(text) {
  return `~~~~text\n${text.replace(/^\s*\n/, "").trimEnd()}\n~~~~`;
}

function rustLicenses() {
  const result = spawnSync(
    "cargo",
    [
      "about",
      "generate",
      "--locked",
      "--fail",
      "--format",
      "json",
      "--manifest-path",
      path.join(root, "src-tauri", "Cargo.toml"),
    ],
    { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 },
  );
  if (result.status !== 0) {
    throw new Error(`cargo about failed:\n${result.stderr}`);
  }
  return JSON.parse(result.stdout).licenses.flatMap((license) => {
    const crates = license.used_by
      .map(({ crate }) => crate)
      .filter((crate) => crate.name !== ownCrate)
      .sort(
        (a, b) =>
          a.name.localeCompare(b.name) || a.version.localeCompare(b.version),
      );
    return crates.length ? [{ ...license, crates }] : [];
  });
}

async function bundledJsModules() {
  const outDir = fs.mkdtempSync(path.join(os.tmpdir(), "hablo-notices-"));
  try {
    await build({
      root,
      logLevel: "error",
      build: {
        outDir,
        emptyOutDir: true,
        license: { fileName: "licenses.json" },
      },
    });
    return JSON.parse(
      fs.readFileSync(path.join(outDir, "licenses.json"), "utf8"),
    );
  } finally {
    fs.rmSync(outDir, { recursive: true, force: true });
  }
}

function crateLine(crate) {
  const links = [`https://crates.io/crates/${crate.name}/${crate.version}`];
  if (crate.repository) links.push(crate.repository);
  return `- ${crate.name} ${crate.version}: ${links.join(", ")}`;
}

// The page that renders this file imports it, so the build needs it to exist.
if (!fs.existsSync(outFile)) fs.writeFileSync(outFile, "");

const rust = rustLicenses();
const js = await bundledJsModules();
const fonts = fs
  .readdirSync(path.join(root, "public", "fonts"))
  .filter((name) => name.endsWith("-LICENSE.txt"))
  .sort();

const mplCrates = rust
  .filter((license) => license.id === "MPL-2.0")
  .flatMap((license) => license.crates)
  .sort((a, b) => a.name.localeCompare(b.name));

const out = [
  "# Third-party notices",
  "",
  "Hablo is released under the MIT License below. It includes the open-source components that follow, each under its own licence.",
  "",
  "This file is generated by `npm run notices` (scripts/generate-notices.mjs). Do not edit it by hand.",
  "",
  "## Hablo (a fork of GladiaFlow)",
  "",
  fence(fs.readFileSync(path.join(root, "LICENSE"), "utf8")),
  "",
  "## Components under the Mozilla Public License 2.0",
  "",
  "Hablo uses these Rust crates unmodified. Their source code is available from crates.io and their repositories:",
  "",
  ...mplCrates.map(crateLine),
  "",
  "The MPL-2.0 text is included with the Rust crates below.",
  "",
  "## Rust crates",
  "",
];

for (const license of rust) {
  out.push(`### ${license.name} (${license.id})`, "", "Used by:", "");
  out.push(...license.crates.map(crateLine), "", fence(license.text), "");
}

out.push("## JavaScript modules", "");
for (const mod of js) {
  out.push(`### ${mod.name} ${mod.version} (${mod.identifier})`, "");
  out.push(
    mod.text ? fence(mod.text) : "No licence text shipped with the package.",
    "",
  );
}

out.push("## Fonts", "");
for (const name of fonts) {
  const text = fs.readFileSync(
    path.join(root, "public", "fonts", name),
    "utf8",
  );
  out.push(`### ${name.replace(/-LICENSE\.txt$/, "")}`, "", fence(text), "");
}

fs.writeFileSync(outFile, `${out.join("\n").trimEnd()}\n`);
console.log(
  `Wrote ${path.relative(root, outFile)}: ${rust.reduce((n, l) => n + l.crates.length, 0)} crate licences, ${js.length} JS modules, ${fonts.length} fonts.`,
);
